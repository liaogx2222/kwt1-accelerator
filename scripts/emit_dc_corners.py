"""Emit Design Compiler corner definitions from a filled SMIC40 binding JSON.

No PVT, library name or operating condition is invented: every value is taken
from the `corners` list that already passed `check_technology.py`. Relative
library paths are resolved against the config file's directory, which matches
check_technology.py:26.

Design Compiler normally consumes compiled `.db` libraries. By default this
tool rewrites a bound `*.lib` path to `*.db` in the generated Tcl and prints the
exact `.lib -> .db` conversions you must perform with Library Compiler on the
server. Use --keep-lib only if your DC build reads `.lib` directly.
"""
import argparse
import json
import sys
from pathlib import Path


def tcl_quote(value):
    text = str(value)
    for old, new in (('\\', '\\\\'), ('"', '\\"'), ('[', '\\['),
                     (']', '\\]'), ('$', '\\$')):
        text = text.replace(old, new)
    return '"' + text + '"'


def resolve(value, base):
    p = Path(value.replace('\\', '/'))
    if not p.is_absolute():
        p = base / p
    return p.as_posix()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--config', type=Path, required=True,
                    help='flow/targets/smic40.binding.filled.json')
    ap.add_argument('--output', type=Path, required=True,
                    help='generated Tcl file, e.g. flow/targets/smic40.dc_corners.tcl')
    ap.add_argument('--keep-lib', action='store_true',
                    help='emit .lib paths unchanged instead of mapping to .db')
    ap.add_argument('--force', action='store_true', help='allow overwriting the output file')
    a = ap.parse_args()

    cfg_path = a.config.resolve()
    if not cfg_path.is_file():
        raise SystemExit('config not found: ' + str(cfg_path))
    out = a.output.resolve()
    if out.exists() and not a.force:
        raise SystemExit('refusing to overwrite existing file (use --force): ' + str(out))

    cfg = json.loads(cfg_path.read_text(encoding='utf-8'))
    corners = cfg.get('corners') or []
    if not corners:
        raise SystemExit('corners is empty: fill the binding and pass check_technology.py first')
    base = cfg_path.parent

    lines = [
        '# GENERATED by scripts/emit_dc_corners.py -- DO NOT hand-edit values.',
        '# Source binding: ' + cfg_path.as_posix(),
        '# Every library path below originates from the AUTHORIZED corners list.',
        '# Consumed by flow/smic40_dc_sta.tcl (KWT_DC_CORNERS_FILE).',
        '',
    ]
    conversions = []
    for i, c in enumerate(corners):
        for required in ('name', 'source', 'standard_cell_liberty'):
            if not c.get(required):
                raise SystemExit('corners[%d].%s is empty' % (i, required))

        def emit_paths(key):
            result = []
            for raw in c.get(key) or []:
                src = resolve(raw, base)
                if not Path(src).is_file():
                    raise SystemExit('bound library file not found: ' + src)
                if a.keep_lib or not src.endswith('.lib'):
                    result.append(src)
                else:
                    db = src[:-4] + '.db'
                    conversions.append((src, db))
                    result.append(db)
            return result

        libs = emit_paths('standard_cell_liberty')
        sram = emit_paths('sram_liberty')
        opcond = c.get('operating_condition', '')
        lines.append('# corner: %s | process=%s voltage_v=%s temperature_c=%s | source=%s' % (
            c['name'], c.get('process'), c.get('voltage_v'),
            c.get('temperature_c'), c['source']))
        lines.append('# time_unit=%s capacitance_unit=%s' % (
            c.get('time_unit'), c.get('capacitance_unit')))
        parts = ['name', tcl_quote(c['name']),
                 'opcond', tcl_quote(opcond),
                 'libs', '[list ' + ' '.join(tcl_quote(x) for x in libs) + ']',
                 'sram_libs', '[list ' + ' '.join(tcl_quote(x) for x in sram) + ']']
        lines.append('lappend KWT_DC_CORNERS [list ' + ' '.join(parts) + ']')
        lines.append('')

    header = ['set KWT_DC_CORNERS [list]', '']
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(header + lines), encoding='utf-8', newline='\n')

    print(json.dumps({
        'output': out.as_posix(),
        'corners': len(corners),
        'lib_to_db_conversions_needed': [{'from': s, 'to': d} for s, d in conversions],
        'operating_condition_note': 'add an optional "operating_condition" key to each '
                                    'corner in the binding JSON if set_operating_conditions '
                                    'must be applied; never guess the name'
    }, indent=2, ensure_ascii=False))
    if conversions and not a.keep_lib:
        print('ACTION: compile each bound .lib to .db with Library Compiler on the server '
              '(or rerun with --keep-lib if your DC reads .lib directly).', file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
